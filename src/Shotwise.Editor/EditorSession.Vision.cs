    /// <summary>Key in <see cref="Annotation.Extra"/> marking shapes generated by Auto Simplify (replaced on regenerate).</summary>
    public const string AutoSimplifyMarker = "shotwiseAutoSimplify";

    private IReadOnlyList<SmartComponent>? _smartComponents;
    private PageSnapshot? _smartSnapshot;
    private IReadOnlyList<RedactionHit> _redactionHits = Array.Empty<RedactionHit>();

    private void InvalidateDerivedCaches()
    {
        if (_smartSnapshot is { } snap && !IsCurrent(ActivePage, snap))
        {
            _smartComponents = null;
            _smartSnapshot = null;
        }
    }

    private Task<T?> RunBackground<T>(string operation, Func<CancellationToken, Task<T?>> work, CancellationToken ct)
    {
        T? result = default;
        var t = RunBackground(operation, async c => { result = await work(c).ConfigureAwait(true); }, ct);
        return t.ContinueWith(_ => result, CancellationToken.None, TaskContinuationOptions.ExecuteSynchronously, TaskScheduler.Default);
    }

    // ------------------------------------------------------------------ Smart Move

    /// <summary>Components detected by the last Smart Move detection on the current base raster (empty when none/stale).</summary>
    public IReadOnlyList<SmartComponent> SmartComponents => _smartComponents ?? Array.Empty<SmartComponent>();

    /// <summary>
    /// Smart Move detection on the flattened base raster. With auto tolerance the service's estimate is used and stored
    /// in <see cref="MoveToolOptions.Tolerance"/>. Reports "no objects found" when nothing is detected.
    /// </summary>
    public Task<int> DetectSmartComponentsAsync(CancellationToken ct = default)
    {
        if (Services.SmartMove is not { } svc)
        {
            ReportUnavailable("Smart Move");
            return Task.FromResult(0);
        }
        var page = ActivePage;
        var snap = Snapshot(page);
        var o = ToolOptions.Move;
        return RunBackground<int>("Smart Move detection", async token =>
        {
            var img = RasterOps.ComposeFlattenedBase(Document, page);
            var tol = o.AutoTolerance ? await svc.AutoToleranceAsync(img, token).ConfigureAwait(true) : o.Tolerance;
            var comps = await svc.DetectAsync(img, tol, token).ConfigureAwait(true);
            if (!IsCurrent(page, snap)) return 0;
            if (o.AutoTolerance) o.Tolerance = tol;
            var size = RasterOps.CanvasPixels(page);
            _smartComponents = comps.Where(c => !c.Bounds.IsEmpty && c.Bounds.Intersect(new RectI(0, 0, size.Width, size.Height)) is { IsEmpty: false }).ToList();
            _smartSnapshot = snap;
            RaiseSmartComponentsDetected(new SmartComponentsDetectedEventArgs(_smartComponents.Count, tol));
            if (_smartComponents.Count == 0)
                Report(new EditorMessage(EditorMessageKind.Info, ErrorCode.NoComponentsFound, "No objects found."));
            Invalidate();
            return _smartComponents.Count;
        }, ct);
    }

    /// <summary>Smallest detected component whose mask covers <paramref name="p"/>.</summary>
    public SmartComponent? SmartComponentAt(Point2 p)
    {
        if (_smartComponents is null) return null;
        var size = RasterOps.CanvasPixels(ActivePage);
        var pi = new PointI((int)Math.Floor(p.X), (int)Math.Floor(p.Y));
        return _smartComponents
            .Where(c => c.Bounds.Contains(pi) && ComponentCovers(c, pi, size))
            .OrderBy(c => (long)c.Bounds.Width * c.Bounds.Height)
            .FirstOrDefault();
    }

    private static bool ComponentCovers(SmartComponent c, PointI p, SizeI canvas)
    {
        if (c.Mask.Width == canvas.Width && c.Mask.Height == canvas.Height) return c.Mask.Contains(p.X, p.Y);
        if (c.Mask.Width == c.Bounds.Width && c.Mask.Height == c.Bounds.Height) return c.Mask.Contains(p.X - c.Bounds.X, p.Y - c.Bounds.Y);
        return true;
    }

    /// <summary>Canvas-sized mask of a component (the contract allows canvas-sized or bounds-sized masks).</summary>
    internal static Mask ComponentCanvasMask(SmartComponent c, SizeI canvas)
    {
        if (c.Mask.Width == canvas.Width && c.Mask.Height == canvas.Height) return c.Mask;
        var m = new Mask(canvas.Width, canvas.Height);
        var local = c.Mask.Width == c.Bounds.Width && c.Mask.Height == c.Bounds.Height;
        var b = c.Bounds.Intersect(new RectI(0, 0, canvas.Width, canvas.Height));
        for (var y = b.Y; y < b.Bottom; y++)
            for (var x = b.X; x < b.Right; x++)
                m.Data[y * canvas.Width + x] = local ? c.Mask[x - c.Bounds.X, y - c.Bounds.Y] : (byte)255;
        return m;
    }

    /// <summary>
    /// Turns a detected component into a movable image object: its pixels are lifted from the base raster and the hole is
    /// auto-filled (inpainting, or the classical fallback). One undo step. Returns the new object id (selected).
    /// </summary>
    public Task<Guid?> LiftSmartComponentAsync(SmartComponent component, CancellationToken ct = default)
    {
        ArgumentNullException.ThrowIfNull(component);
        var page = ActivePage;
        var snap = Snapshot(page);
        var hq = ToolOptions.Move.HighQuality;
        return RunBackground<Guid?>("Smart Move", async token =>
        {
            var size = RasterOps.CanvasPixels(page);
            var mask = ComponentCanvasMask(component, size);
            var baseRaster = RasterOps.ComposeBase(Document, page);
            var region = component.Bounds.Intersect(baseRaster.Bounds);
            if (region.IsEmpty) return null;
            var lifted = RasterOps.ExtractMasked(baseRaster, mask, region);
            var filled = await FillHoleAsync(baseRaster, page, mask, autoFill: true, hq, token).ConfigureAwait(true);
            if (!IsCurrent(page, snap)) return null;
            var asset = Document.Assets.AddImage(lifted);
            var obj = new ImageAnnotation { Asset = asset, Start = new Point2(region.X, region.Y), End = new Point2(region.Right, region.Bottom) };
            var add = new AssetHoldingCommand(new AddAnnotationCommand(page.Id, obj, label: "Smart Move"), new[] { asset });
            var remaining = _smartComponents?.Where(c => c.Id != component.Id).ToList();
            if (!CommitBaseRaster(page, snap, filled, "Smart Move", new IEditCommand[] { add })) return null;
            if (remaining is not null)
            {
                // the other components are still valid: the base only changed inside the lifted component
                _smartComponents = remaining;
                _smartSnapshot = Snapshot(page);
            }
            Selection.Select(obj.Id);
            return obj.Id;
        }, ct);
    }

    // ------------------------------------------------------------------ Smart Redact

    /// <summary>Hits of the last Smart Redact detection (all categories, including disabled ones).</summary>
    public IReadOnlyList<RedactionHit> LastRedactionHits => _redactionHits;

    /// <summary>
    /// Smart Redact: detects sensitive data on the rendered page and covers enabled categories with blur objects
    /// (mode/colour from <see cref="Page.SmartRedact"/>). Replaces earlier Smart Redact objects. Returns the hit count.
    /// </summary>
    public Task<int> SmartRedactAsync(IReadOnlySet<RedactCategory>? categories = null, CancellationToken ct = default)
    {
        if (Services.SmartRedact is not { } svc)
        {
            ReportUnavailable("Smart Redact");
            return Task.FromResult(0);
        }
        var page = ActivePage;
        var cats = categories ?? page.SmartRedact.Categories.ToHashSet();
        var all = Enum.GetValues<RedactCategory>().ToHashSet();
        return RunBackground<int>("Smart Redact", async token =>
        {
            var img = TryRender(new Shotwise.Core.Documents.RenderOptions()) ?? RasterOps.ComposeFlattenedBase(Document, page);
            var hits = await svc.FindAsync(img, all, token).ConfigureAwait(true);
            if (!ReferenceEquals(page, ActivePage)) return 0;
            _redactionHits = hits.ToList();
            RaiseRedactionsFound(new RedactionsFoundEventArgs(_redactionHits));
            if (_redactionHits.Count == 0)
            {
                Report(new EditorMessage(EditorMessageKind.Info, ErrorCode.NoRedactionsFound, "No sensitive data found."));
                return 0;
            }
            ApplyRedactions(cats, page.SmartRedact.Mode, page.SmartRedact.SolidColor, "Smart Redact");
            return _redactionHits.Count;
        }, ct);
    }

    /// <summary>Covers the given hits with Smart Redact blur objects (replacing existing ones). Also used directly by tests/automation.</summary>
    public void ApplyRedactionHits(IEnumerable<RedactionHit> hits, BlurKind? mode = null, Argb? color = null)
    {
        ArgumentNullException.ThrowIfNull(hits);
        _redactionHits = hits.ToList();
        var s = ActivePage.SmartRedact;
        ApplyRedactions(_redactionHits.Select(h => h.Category).ToHashSet(), mode ?? s.Mode, color ?? s.SolidColor, "Smart Redact");
    }

    private void ApplyRedactions(IReadOnlySet<RedactCategory> enabled, BlurKind mode, Argb color, string label)
    {
        var page = ActivePage;
        var existing = page.Annotations.OfType<BlurAnnotation>().Where(b => b.Category is not null).Select(b => b.Id).ToList();
        var blurs = _redactionHits.Where(h => enabled.Contains(h.Category)).Select(h => CreateRedactionBlur(h, mode, color)).ToList();
        var settings = page.SmartRedact with { Enabled = true, Categories = enabled.ToList(), Mode = mode, SolidColor = color };
        var cmds = new List<IEditCommand>();
        if (existing.Count > 0) cmds.Add(new RemoveAnnotationsByIdCommand(page.Id, existing, label));
        if (blurs.Count > 0) cmds.Add(new AddAnnotationsCommand(page.Id, blurs, label));
        cmds.Add(new SetPageValueCommand<SmartRedactSettings>(page.Id, p => p.SmartRedact, (p, v) => p.SmartRedact = v, settings, label));
        Selection.ClearObjects();
        ExecuteComposite(label, cmds);
    }

    private BlurAnnotation CreateRedactionBlur(RedactionHit h, BlurKind mode, Argb color)
    {
        var b = CreateFromStyle<BlurAnnotation>(ToolKind.Blur);
        var r = h.Bounds.Normalize().Inflate(2).Intersect(ActivePage.CanvasRect.Inflate(2));
        b.Start = r.TopLeft;
        b.End = r.BottomRight;
        b.Region = h.Category == RedactCategory.Face ? ShapeKind.Ellipse : ShapeKind.Rectangle;
        b.Mode = mode;
        b.SolidColor = color;
        b.Category = h.Category;
        b.Shadow = null;
        b.Stroke = StrokeStyle.None;
        return b;
    }

    /// <summary>Review pane toggle: shows/hides the redactions of one category (from the last detection).</summary>
    public void SetSmartRedactCategory(RedactCategory category, bool enabled)
    {
        var s = ActivePage.SmartRedact;
        var set = s.Categories.ToHashSet();
        if (enabled ? !set.Add(category) : !set.Remove(category)) return;
        ApplyRedactions(set, s.Mode, s.SolidColor, enabled ? "Show redaction" : "Hide redaction");
    }

    /// <summary>Redaction type (blur / pixelate / solid + colour) for all Smart Redact objects.</summary>
    public void SetSmartRedactMode(BlurKind mode, Argb color)
    {
        var page = ActivePage;
        var ids = page.Annotations.OfType<BlurAnnotation>().Where(b => b.Category is not null).Select(b => b.Id).ToList();
        var cmds = new List<IEditCommand>();
        if (ids.Count > 0) cmds.Add(ModifyAnnotationsCommand.Create(page, ids, a => { var b = (BlurAnnotation)a; b.Mode = mode; b.SolidColor = color; }, "Redaction type"));
        cmds.Add(new SetPageValueCommand<SmartRedactSettings>(page.Id, p => p.SmartRedact, (p, v) => p.SmartRedact = v, page.SmartRedact with { Mode = mode, SolidColor = color }, "Redaction type"));
        ExecuteComposite("Redaction type", cmds);
    }

    /// <summary>"Clear": removes every Smart Redact object and closes the review.</summary>
    public void ClearSmartRedact()
    {
        var page = ActivePage;
        var ids = page.Annotations.OfType<BlurAnnotation>().Where(b => b.Category is not null).Select(b => b.Id).ToList();
        var cmds = new List<IEditCommand>();
        if (ids.Count > 0) cmds.Add(new RemoveAnnotationsByIdCommand(page.Id, ids, "Clear redactions"));
        if (page.SmartRedact.Enabled)
            cmds.Add(new SetPageValueCommand<SmartRedactSettings>(page.Id, p => p.SmartRedact, (p, v) => p.SmartRedact = v, page.SmartRedact with { Enabled = false }, "Clear redactions"));
        _redactionHits = Array.Empty<RedactionHit>();
        ExecuteComposite("Clear redactions", cmds);
    }

    /// <summary>"Done": keeps the redaction objects and closes the review.</summary>
    public void FinishSmartRedact()
    {
        var page = ActivePage;
        if (!page.SmartRedact.Enabled) return;
        Execute(new SetPageValueCommand<SmartRedactSettings>(page.Id, p => p.SmartRedact, (p, v) => p.SmartRedact = v, page.SmartRedact with { Enabled = false }, "Smart Redact done"));
    }

