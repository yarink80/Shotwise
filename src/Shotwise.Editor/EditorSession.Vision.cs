    /// <summary>Built-in Simplify palettes (our own colour choices).</summary>
    public static Palette BuiltInSimplifyPalette(SimplifyPaletteKind kind) => kind switch
    {
        SimplifyPaletteKind.Dark => new Palette { Id = "simplify-dark", Name = "Dark", IsBuiltIn = true, Colors = new() { new(0xFF1F2430), new(0xFF2E3440), new(0xFF4C566A), new(0xFF81A1C1), new(0xFFD8DEE9), new(0xFFBF616A), new(0xFFA3BE8C), new(0xFFEBCB8B) } },
        SimplifyPaletteKind.Grayscale => new Palette { Id = "simplify-gray", Name = "Grayscale", IsBuiltIn = true, Colors = new() { new(0xFFF5F5F5), new(0xFFE0E0E0), new(0xFFBDBDBD), new(0xFF9E9E9E), new(0xFF757575), new(0xFF616161), new(0xFF424242), new(0xFF212121) } },
        _ => new Palette { Id = "simplify-light", Name = "Light", IsBuiltIn = true, Colors = new() { new(0xFFFFFFFF), new(0xFFF1F3F6), new(0xFFDDE3EA), new(0xFFB8C4D3), new(0xFF7A8CA5), new(0xFF4A90D9), new(0xFF5CB85C), new(0xFFF0AD4E) } },
    };

    /// <summary>Palette used by Simplify (last auto-simplify palette, else from the page settings).</summary>
    public Palette SimplifyPalette { get; private set; } = BuiltInSimplifyPalette(SimplifyPaletteKind.Light);

    private async Task<Palette> ResolveSimplifyPaletteAsync(SimplifySettings s, BgraImage img, ISimplifyService svc, CancellationToken ct) => s.Palette switch
    {
        SimplifyPaletteKind.ImageColors => await svc.DominantColorsAsync(img, 8, ct).ConfigureAwait(true),
        SimplifyPaletteKind.Custom when s.CustomColors.Count > 0 => new Palette { Id = "simplify-custom", Name = "Custom", Colors = s.CustomColors.ToList() },
        _ => BuiltInSimplifyPalette(s.Palette),
    };

    /// <summary>Colour of palette entry <paramref name="index"/> (wraps).</summary>
    public Argb SimplifyColor(int index)
        => SimplifyPalette.Colors.Count == 0 ? Argb.LightGray : SimplifyPalette.Colors[((index % SimplifyPalette.Colors.Count) + SimplifyPalette.Colors.Count) % SimplifyPalette.Colors.Count];

    /// <summary>
    /// Auto Simplify: detects text/UI regions and replaces previous auto shapes with simplified shapes (detail, palette,
    /// opacity, lock per <see cref="Page.Simplify"/>). One undo step; enables Auto Simplify on the page.
    /// </summary>
    public Task<int> AutoSimplifyAsync(CancellationToken ct = default)
    {
        if (Services.Simplify is not { } svc)
        {
            ReportUnavailable("Auto Simplify");
            return Task.FromResult(0);
        }
        var page = ActivePage;
        var snap = Snapshot(page);
        var settings = page.Simplify;
        return RunBackground<int>("Auto Simplify", async token =>
        {
            var img = RasterOps.ComposeFlattenedBase(Document, page);
            var palette = await ResolveSimplifyPaletteAsync(settings, img, svc, token).ConfigureAwait(true);
            var shapes = await svc.GenerateAsync(img, Math.Clamp(settings.Detail, 1, 10), palette, token).ConfigureAwait(true);
            if (!IsCurrent(page, snap)) return 0;
            SimplifyPalette = palette;
            var marker = JsonSerializer.SerializeToElement(true);
            var generated = new List<Annotation>();
            foreach (var src in shapes)
            {
                var a = (SimplifyShapeAnnotation)src.DeepClone();
                a.Id = Guid.NewGuid();
                a.Opacity = Math.Clamp(settings.Opacity, 0, 1);
                a.IsLocked = settings.LockObjects;
                if (!a.Fill.IsVisible) a.Fill = FillStyle.Solid(SimplifyColor(a.PaletteIndex));
                a.Extra = new Dictionary<string, JsonElement>(a.Extra ?? new()) { [AutoSimplifyMarker] = marker };
                generated.Add(a);
            }
            ReplaceAutoSimplifyShapes(generated, settings with { AutoSimplifyEnabled = true }, "Auto Simplify");
            return generated.Count;
        }, ct);
    }

    private void ReplaceAutoSimplifyShapes(IReadOnlyList<Annotation> generated, SimplifySettings settings, string label)
    {
        var page = ActivePage;
        var old = page.Annotations.Where(IsAutoSimplifyShape).Select(a => a.Id).ToList();
        var cmds = new List<IEditCommand>();
        if (old.Count > 0) cmds.Add(new RemoveAnnotationsByIdCommand(page.Id, old, label));
        if (generated.Count > 0) cmds.Add(new AddAnnotationsCommand(page.Id, generated, label));
        cmds.Add(new SetPageValueCommand<SimplifySettings>(page.Id, p => p.Simplify, (p, v) => p.Simplify = v, settings, label));
        Selection.ClearObjects();
        ExecuteComposite(label, cmds);
    }

    public static bool IsAutoSimplifyShape(Annotation a) => a is SimplifyShapeAnnotation && a.Extra?.ContainsKey(AutoSimplifyMarker) == true;

    /// <summary>Turns Auto Simplify off and removes the generated shapes (manual simplify shapes stay).</summary>
    public void DisableAutoSimplify() => ReplaceAutoSimplifyShapes(Array.Empty<Annotation>(), ActivePage.Simplify with { AutoSimplifyEnabled = false }, "Auto Simplify off");

    /// <summary>
    /// Updates Simplify settings (one undo step). Opacity / lock changes are applied to existing auto shapes; when
    /// <paramref name="regenerate"/> and Auto Simplify is on, shapes are regenerated (detail / palette changes).
    /// </summary>
    public Task SetSimplifySettingsAsync(SimplifySettings settings, bool regenerate, CancellationToken ct = default)
    {
        ArgumentNullException.ThrowIfNull(settings);
        var page = ActivePage;
        var autoIds = page.Annotations.Where(IsAutoSimplifyShape).Select(a => a.Id).ToList();
        var cmds = new List<IEditCommand> { new SetPageValueCommand<SimplifySettings>(page.Id, p => p.Simplify, (p, v) => p.Simplify = v, settings, "Simplify settings") };
        if (autoIds.Count > 0)
            cmds.Add(ModifyAnnotationsCommand.Create(page, autoIds, a => { a.Opacity = Math.Clamp(settings.Opacity, 0, 1); a.IsLocked = settings.LockObjects; }, "Simplify settings"));
        ExecuteComposite("Simplify settings", cmds);
        return regenerate && settings.AutoSimplifyEnabled ? AutoSimplifyAsync(ct) : Task.CompletedTask;
    }

    // ------------------------------------------------------------------ Grab Text / Edit Text

    /// <summary>
    /// Grab Text: OCR of the rendered page (what the user sees) in <paramref name="region"/> (default: pixel selection,
    /// else whole page). Raises <see cref="TextRecognized"/> and returns the result (null when unavailable/cancelled).
    /// </summary>
    public Task<OcrResult?> GrabTextAsync(Rect2? region = null, CancellationToken ct = default)
    {
        if (Services.Ocr is not { } ocr)
        {
            ReportUnavailable("Grab Text");
            return Task.FromResult<OcrResult?>(null);
        }
        var page = ActivePage;
        var r = (region ?? Selection.PixelBounds)?.Normalize().Intersect(page.CanvasRect);
        if (r is { IsEmpty: true }) r = null;
        var lang = ToolOptions.GrabText.Language;
        return RunBackground<OcrResult?>("Grab Text", async token =>
        {
            var img = TryRender(new Shotwise.Core.Documents.RenderOptions()) ?? RasterOps.ComposeFlattenedBase(Document, page);
            var result = await ocr.RecognizeAsync(img, r, lang, token).ConfigureAwait(true);
            RaiseTextRecognized(new TextRecognizedEventArgs(result, r));
            if (result.Lines.Count == 0)
                Report(new EditorMessage(EditorMessageKind.Info, ErrorCode.OcrFailed, "No text was recognized."));
            return result;
        }, ct);
    }

    /// <summary>
    /// Edit Text: recognised lines in <paramref name="region"/> become editable text objects with matched colour, size
    /// and weight; the original text pixels are inpainted away. One undo step. Returns the number of text objects.
    /// </summary>
    public Task<int> EditTextAsync(Rect2? region = null, CancellationToken ct = default)
    {
        if (Services.TextEdit is not { } svc)
        {
            ReportUnavailable("Edit Text");
            return Task.FromResult(0);
        }
        var page = ActivePage;
        var snap = Snapshot(page);
        var r = (region ?? Selection.PixelBounds)?.Normalize().Intersect(page.CanvasRect);
        if (r is { IsEmpty: true }) r = null;
        return RunBackground<int>("Edit Text", async token =>
        {
            var img = RasterOps.ComposeFlattenedBase(Document, page);
            var lines = await svc.AnalyzeAsync(img, r, token).ConfigureAwait(true);
            if (lines.Count == 0)
            {
                Report(new EditorMessage(EditorMessageKind.Info, ErrorCode.OcrFailed, "No text was recognized."));
                return 0;
            }
            var size = RasterOps.CanvasPixels(page);
            var hole = Mask.FromRects(size.Width, size.Height, lines.Select(l => l.Line.Bounds.Inflate(2).ToRectIOutward()));
            var baseRaster = RasterOps.ComposeBase(Document, page);
            var filled = await FillHoleAsync(baseRaster, page, hole, autoFill: true, highQuality: true, token).ConfigureAwait(true);
            var texts = lines.Select(l => CreateRecognizedText(l.Line, l.Style)).ToList();
            var add = new AddAnnotationsCommand(page.Id, texts, "Edit text");
            if (!CommitBaseRaster(page, snap, filled, "Edit text", new IEditCommand[] { add })) return 0;
            Selection.Set(texts.Select(t => t.Id));
            return texts.Count;
        }, ct);
    }

    private static Annotation CreateRecognizedText(OcrLine line, TextStyleSample style)
    {
        var b = line.Bounds.Normalize();
        var font = string.IsNullOrWhiteSpace(style.SuggestedFont) ? "Segoe UI" : style.SuggestedFont;
        var size = style.FontSizePx > 0 ? style.FontSizePx : Math.Max(6, b.Height * 0.75);
        return new TextAnnotation
        {
            Start = b.TopLeft,
            End = b.BottomRight,
            Text = RichText.FromPlain(line.Text, font, size, style.TextColor, style.Bold),
            TextStyle = TextLayoutStyle.Default with { Padding = Thickness2.Zero, VAlign = VerticalAlign.Middle, AutoSize = true },
            DeselectBehavior = TextDeselectBehavior.Keep,
            Stroke = StrokeStyle.None,
            Fill = FillStyle.None,
        };
    }
